export function translate(language: Language, text: string, values?: Record<string, string | number>) {
  let result = language === "vi" ? vi[text] ?? text : text;
  for (const [key, value] of Object.entries(values ?? {})) result = result.replaceAll(`{${key}}`, String(value));
  return result;
}
